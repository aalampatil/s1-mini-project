CREATE TABLE flights (
  flight_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_no       VARCHAR2(20) NOT NULL UNIQUE,
  origin          VARCHAR2(80) NOT NULL,
  destination     VARCHAR2(80) NOT NULL,
  departure_time  TIMESTAMP NOT NULL,
  arrival_time    TIMESTAMP NOT NULL,
  base_fare       NUMBER(10, 2) NOT NULL CHECK (base_fare > 0),
  status          VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
  CONSTRAINT flights_time_ck CHECK (arrival_time > departure_time),
  CONSTRAINT flights_status_ck CHECK (status IN ('SCHEDULED', 'BOARDING', 'DEPARTED', 'CANCELLED'))
);

CREATE TABLE seats (
  seat_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id  NUMBER NOT NULL REFERENCES flights(flight_id) ON DELETE CASCADE,
  seat_no    VARCHAR2(5) NOT NULL,
  seat_class VARCHAR2(20) DEFAULT 'ECONOMY' NOT NULL,
  status     VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
  CONSTRAINT seats_flight_no_uq UNIQUE (flight_id, seat_no),
  CONSTRAINT seats_class_ck CHECK (seat_class IN ('ECONOMY', 'BUSINESS')),
  CONSTRAINT seats_status_ck CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED'))
);

CREATE TABLE passengers (
  passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    VARCHAR2(120) NOT NULL,
  email        VARCHAR2(160) NOT NULL UNIQUE,
  phone        VARCHAR2(30),
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE bookings (
  booking_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_ref     VARCHAR2(20) NOT NULL UNIQUE,
  flight_id       NUMBER NOT NULL REFERENCES flights(flight_id),
  seat_id         NUMBER NOT NULL REFERENCES seats(seat_id),
  passenger_id    NUMBER NOT NULL REFERENCES passengers(passenger_id),
  fare_amount     NUMBER(10, 2) NOT NULL CHECK (fare_amount > 0),
  refund_amount   NUMBER(10, 2) DEFAULT 0 NOT NULL,
  status          VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
  booked_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  cancelled_at    TIMESTAMP,
  CONSTRAINT bookings_status_ck CHECK (status IN ('CONFIRMED', 'CANCELLED')),
  CONSTRAINT bookings_seat_once_uq UNIQUE (flight_id, seat_id)
);

CREATE INDEX seats_flight_status_ix ON seats(flight_id, status);
CREATE INDEX bookings_passenger_ix ON bookings(passenger_id);
